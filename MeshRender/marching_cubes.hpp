/**
 * @brief 从体数据中提取等值面
 *
 * 遍历每个体素单元，根据 8 个角点与等值面的大小关系
 * 查表确定三角形拓扑，在边上线性插值得到顶点位置。
 *
 * @param volume      体数据（VolumeBuildResult）
 * @param isovalue    等值面阈值（8-bit，0-255）
 * @param spacingScale 间距缩放因子（1.0=原始物理尺寸，<1 可缩小模型）
 * @return MeshData   提取的三角网格
 */
inline MeshData extractIsosurface(const std::vector<uint8_t>& buffer,
                                   int w, int h, int d,
                                   const double spacing[3],
                                   const double origin[3],
                                   float isovalue,
                                   float spacingScale = 1.0f) {
    MeshData mesh;
    mesh.name = "Isosurface";

    if (buffer.empty() || w <= 0 || h <= 0 || d <= 0)
        return mesh;

    float sx = (float)spacing[0] * spacingScale;
    float sy = (float)spacing[1] * spacingScale;
    float sz = (float)spacing[2] * spacingScale;
    float ox = (float)origin[0];
    float oy = (float)origin[1];
    float oz = (float)origin[2];

    // 体素 8 个角点的偏移定义（标准 Paul Bourke 编号）
    //   底面 z=0: v0(0,0,0) v1(1,0,0) v2(1,1,0) v3(0,1,0)
    //   顶面 z=1: v4(0,0,1) v5(1,0,1) v6(1,1,1) v7(0,1,1)
    // x=列, y=行, z=切片方向
    const int cornerOffset[8][3] = {
        {0, 0, 0},  // v0
        {1, 0, 0},  // v1
        {1, 1, 0},  // v2
        {0, 1, 0},  // v3
        {0, 0, 1},  // v4
        {1, 0, 1},  // v5
        {1, 1, 1},  // v6
        {0, 1, 1},  // v7
    };

    // 12 条边的端点索引
    const int edgeEndpoints[12][2] = {
        {0, 1}, {1, 2}, {2, 3}, {3, 0},  // 底面 4 条边
        {4, 5}, {5, 6}, {6, 7}, {7, 4},  // 顶面 4 条边
        {0, 4}, {1, 5}, {2, 6}, {3, 7},  // 竖直 4 条边
    };

    // 预分配网格缓冲区（避免反复 realloc）
    // 估算：约 10% 的体素会产生三角形，每个体素最多 5 个三角形 = 15 个顶点
    size_t estVerts = (size_t)(w - 1) * (h - 1) * (d - 1) * 2;
    mesh.vertices.reserve(estVerts);
    mesh.indices.reserve(estVerts);

    // 遍历所有体素单元
    for (int z = 0; z < d - 1; z++) {
        // 每 20 层输出一次进度
        if (z % 20 == 0) {
            std::cout << "  MC 进度: " << z << "/" << (d - 1)
                      << " (顶点: " << mesh.vertexCount() << ")" << std::endl;
        }
        for (int y = 0; y < h - 1; y++) {
            for (int x = 0; x < w - 1; x++) {

                // 采样 8 个角点（直接索引，无需边界检查——循环保证在界内）
                float val[8];
                int cubeConfig = 0;

                for (int i = 0; i < 8; i++) {
                    int cx = x + cornerOffset[i][0];
                    int cy = y + cornerOffset[i][1];
                    int cz = z + cornerOffset[i][2];
                    val[i] = (float)buffer[(size_t)cz * w * h + (size_t)cy * w + (size_t)cx];
                    if (val[i] < isovalue)
                        cubeConfig |= (1 << i);
                }

                // 没有等值面穿过此体素
                if (cubeConfig == 0 || cubeConfig == 255)
                    continue;

                int edges = edgeTable[cubeConfig];
                if (edges == 0)
                    continue;

                // 计算每条边上的交点（线性插值）
                float edgeVertex[12][3] = {{0}};
                float edgeNormal[12][3] = {{0}};
                bool edgeValid[12] = {false};

                for (int e = 0; e < 12; e++) {
                    if (!(edges & (1 << e)))
                        continue;

                    int a = edgeEndpoints[e][0];
                    int b = edgeEndpoints[e][1];

                    float va = val[a];
                    float vb = val[b];
                    float diff = vb - va;
                    float t = (std::abs(diff) < 1e-6f) ? 0.5f : (isovalue - va) / diff;

                    // 角点坐标（物理空间）
                    int ax = x + cornerOffset[a][0];
                    int ay = y + cornerOffset[a][1];
                    int az = z + cornerOffset[a][2];
                    int bx = x + cornerOffset[b][0];
                    int by = y + cornerOffset[b][1];
                    int bz = z + cornerOffset[b][2];

                    edgeVertex[e][0] = ox + (ax + t * (bx - ax)) * sx;
                    edgeVertex[e][1] = oy + (ay + t * (by - ay)) * sy;
                    edgeVertex[e][2] = oz + (az + t * (bz - az)) * sz;

                    // 梯度法线（在交点附近采样）
                    int mx = (int)(ax + t * (bx - ax) + 0.5f);
                    int my = (int)(ay + t * (by - ay) + 0.5f);
                    int mz = (int)(az + t * (bz - az) + 0.5f);
                    computeGradient(buffer, mx, my, mz, w, h, d, edgeNormal[e]);

                    edgeValid[e] = true;
                }

                // 根据三角形表生成三角形
                const int* tri = triTable[cubeConfig];
                for (int i = 0; i < 16 && tri[i] != -1; i += 3) {
                    int e0 = tri[i];
                    int e1 = tri[i + 1];
                    int e2 = tri[i + 2];

                    if (!edgeValid[e0] || !edgeValid[e1] || !edgeValid[e2])
                        continue;

                    uint32_t base = (uint32_t)mesh.vertices.size();

                    Vertex v0, v1, v2;
                    for (int k = 0; k < 3; k++) {
                        v0.position[k] = edgeVertex[e0][k];
                        v1.position[k] = edgeVertex[e1][k];
                        v2.position[k] = edgeVertex[e2][k];
                        v0.normal[k] = edgeNormal[e0][k];
                        v1.normal[k] = edgeNormal[e1][k];
                        v2.normal[k] = edgeNormal[e2][k];
                    }
                    // 纹理坐标用归一化的物理坐标
                    v0.texcoord[0] = edgeVertex[e0][0] / (w * sx + 1e-6f);
                    v0.texcoord[1] = edgeVertex[e0][1] / (h * sy + 1e-6f);
                    v1.texcoord[0] = edgeVertex[e1][0] / (w * sx + 1e-6f);
                    v1.texcoord[1] = edgeVertex[e1][1] / (h * sy + 1e-6f);
                    v2.texcoord[0] = edgeVertex[e2][0] / (w * sx + 1e-6f);
                    v2.texcoord[1] = edgeVertex[e2][1] / (h * sy + 1e-6f);

                    mesh.vertices.push_back(v0);
                    mesh.vertices.push_back(v1);
                    mesh.vertices.push_back(v2);

                    mesh.indices.push_back(base);
                    mesh.indices.push_back(base + 1);
                    mesh.indices.push_back(base + 2);
                }
            }
        }
    }

    return mesh;
}

