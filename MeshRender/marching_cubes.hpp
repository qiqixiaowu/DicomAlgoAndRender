/**
 * @brief 采样体数据，带边界检查
 * @param buffer  体数据缓冲区
 * @param w,h,d   体数据尺寸
 * @return 8-bit 体素值，越界返回 0
 */
inline uint8_t sampleVolume(const std::vector<uint8_t>& buffer,
                            int x, int y, int z,
                            int w, int h, int d) {
    if (x < 0 || x >= w || y < 0 || y >= h || z < 0 || z >= d)
        return 0;
    return buffer[(size_t)z * w * h + (size_t)y * w + (size_t)x];
}

/**
 * @brief 计算体素梯度（中心差分），用作顶点法线
 * @return 归一化的法线 [x,y,z]
 */
inline void computeGradient(const std::vector<uint8_t>& buffer,
                            int x, int y, int z,
                            int w, int h, int d,
                            float outNormal[3]) {
    float gx = (float)sampleVolume(buffer, x+1, y, z, w, h, d)
             - (float)sampleVolume(buffer, x-1, y, z, w, h, d);
    float gy = (float)sampleVolume(buffer, x, y+1, z, w, h, d)
             - (float)sampleVolume(buffer, x, y-1, z, w, h, d);
    float gz = (float)sampleVolume(buffer, x, y, z+1, w, h, d)
             - (float)sampleVolume(buffer, x, y, z-1, w, h, d);

    // 梯度方向指向密度增大方向，法线指向密度减小方向（即 -gradient）
    float len = std::sqrt(gx*gx + gy*gy + gz*gz);
    if (len > 1e-6f) {
        float inv = -1.0f / len;  // 负号：法线朝外
        outNormal[0] = gx * inv;
        outNormal[1] = gy * inv;
        outNormal[2] = gz * inv;
    } else {
        outNormal[0] = 0;
        outNormal[1] = 1;
        outNormal[2] = 0;
    }
}

